import { mkdtempSync, writeFileSync, readFileSync, mkdirSync } from "node:fs";
import { resolve, join, dirname, relative } from "node:path";
import { spawn } from "node:child_process";
import { resolveBoundExecutionContext } from "../../dist/execution-context.js";
import { Feature } from "../../dist/feature.js";
import { copilotHarness } from "../../dist/harnesses/copilot.js";
import { resolveCommand } from "../../dist/platform-command.js";
import { observeProcess, stopOwnedProcess } from "../../dist/platform-process.js";

if (process.argv[2] !== "--infer" || !process.argv[3]) throw new Error("Require --infer RETAINED_ROOT");
const root = resolve(process.argv[3]);
const count = Number(process.env.GIT_CONFIG_COUNT ?? 0);
process.env[`GIT_CONFIG_KEY_${count}`] = "safe.directory";
process.env[`GIT_CONFIG_VALUE_${count}`] = `${root.replaceAll("\\", "/")}/*`;
process.env.GIT_CONFIG_COUNT = String(count + 1);
const execution = resolveBoundExecutionContext({ implementationRoot: join(root, "code"), storeRoot: join(root, "store"), featureId: "product", componentId: "api", assignmentId: "assignment", change: "demo" });
const feature = new Feature(join(root, "code"), undefined, execution);
const store = feature.runner.invocationScope("demo");
const component = store.contextPaths.find(path => path.endsWith("1"));
if (!component) throw new Error("Expected retained component snapshot");
const targets = ["tasks.md", "execution.yaml"].map(name => join(component, "components/api/openspec/changes/demo", name));
const aclControl = process.argv.includes("--acl-control");
const shortControl = process.argv.includes("--short-control");
if (aclControl || shortControl) {
  const copies = targets.map(path => {
    const suffix = relative(join(store.runtimeDir, "component-context"), path);
    if (suffix.startsWith("..")) throw new Error("Snapshot outside approved component context");
    const copy = join(store.runtimeDir, shortControl ? "c" : "component-readctx", suffix);
    if (copy.length !== path.length - (shortControl ? 16 : 0)) throw new Error("Unexpected control path length");
    mkdirSync(dirname(copy), { recursive: true });
    writeFileSync(copy, readFileSync(path), { flag: "wx" });
    return copy;
  });
  if (shortControl) targets.splice(0, targets.length, ...copies); else targets.push(...copies);
}
const exactReadControl = process.argv.includes("--exact-read-control") || aclControl || shortControl;
const sameCwdIndex = process.argv.indexOf("--same-cwd");
const cwd = sameCwdIndex !== -1 ? resolve(process.argv[sameCwdIndex + 1]) : mkdtempSync(join(root, "read-probe-"));
if (!cwd.startsWith(root + "\\") && !cwd.startsWith(root + "/")) throw new Error("Probe working directory must stay in retained disposable root");
const prompt = `This is one read-only permission verification, not an implementation or review job. Use ONLY the native read tool to read all ${targets.length} exact files below, with one read call for each path. Do not use shell, edits, writes, commits, begin/report, or any other tool. Then summarize their actual contents (HELLO task and execution agent/task), and state separately which reads succeeded or were denied. Stop after this.\n${targets.join("\n")}`;
const settings = feature.read("demo").approval.review;
const invocation = copilotHarness.initialInvocation(settings, cwd, execution.implementation.common, prompt, undefined, store);
if (exactReadControl) invocation.args.push(...targets.flatMap(path => ["--allow-tool", `read(${path})`]));
const command = resolveCommand(invocation);
const child = spawn(command.executable, command.args, { cwd, env: command.env, windowsHide: true, stdio: ["ignore", "pipe", "pipe"] });
const identity = observeProcess(child.pid);
let stdout = "", stderr = "", timedOut = false, termination;
const collect = (existing, chunk) => (existing + chunk.toString()).slice(0, 262144);
child.stdout.on("data", chunk => { stdout = collect(stdout, chunk); });
child.stderr.on("data", chunk => { stderr = collect(stderr, chunk); });
const timer = setTimeout(async () => { timedOut = true; if (identity) termination = await stopOwnedProcess({ pid: child.pid, createdAt: identity.createdAt, timeoutMs: 3000 }); else child.kill(); }, 120000);
const exitCode = await new Promise((done, reject) => { child.once("error", reject); child.once("close", done); });
clearTimeout(timer);
const prefix = shortControl ? "short-control-" : aclControl ? "acl-control-" : exactReadControl ? "exact-control-" : "";
writeFileSync(join(cwd, `${prefix}stdout.log`), stdout);
writeFileSync(join(cwd, `${prefix}stderr.log`), stderr);
const result = { cwd, experimentalShortPathControl: shortControl, experimentalAclControl: aclControl, experimentalExactReadControl: exactReadControl, appendedPermissions: exactReadControl ? targets.map(path => `read(${path})`) : [], targets: targets.map(path => ({ path, length: path.length, expectedBytes: readFileSync(path).length })), executable: command.executable, model: settings.model, exitCode, timedOut, termination, status: "INSPECT_NATIVE_READ_EVIDENCE", lifecycleClaim: false };
writeFileSync(join(cwd, `${prefix}receipt.json`), JSON.stringify(result, null, 2));
console.log(JSON.stringify(result));
if (timedOut || exitCode !== 0) process.exitCode = 1;
